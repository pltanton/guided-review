type harness struct {
	t         *testing.T
	repo      *testrepo.Repo
	cache     string
	gitconfig string
	glab      func(context.Context, ...string) ([]byte, error)
	gh        func(context.Context, ...string) ([]byte, error)
}

func newHarness(t *testing.T) *harness {
	home := t.TempDir()
	gitconfig := filepath.Join(home, ".gitconfig")
	if err := os.WriteFile(gitconfig, nil, 0o644); err != nil {
		t.Fatal(err)
	}
	t.Setenv("HOME", home)
	t.Setenv("XDG_CONFIG_HOME", filepath.Join(home, ".config"))
	t.Setenv("GIT_CONFIG_GLOBAL", gitconfig)
	t.Setenv("GIT_CONFIG_SYSTEM", os.DevNull)
	tr := testrepo.New(t)
	tr.Write(
		"api/transfer.go",
		"package api\n\nfunc Transfer(a, b int) int {\n\treturn a + b\n}\n",
	)
	tr.Commit("base")
	tr.Git("checkout", "-q", "-b", "feature")
	tr.Write(
		"api/transfer.go",
		"package api\n\nfunc Transfer(a, b int) int {\n\tif a < 0 {\n\t\treturn 0\n\t}\n\treturn a + b\n}\n",
	)
	tr.Write(
		"api/transfer.pb.go",
		"// Code generated by protoc-gen-go. DO NOT EDIT.\npackage api\n",
	)
	tr.Write("wire.go", "package api\n\nvar _ = Transfer\n")
	tr.Commit("guard")
	return &harness{t: t, repo: tr, cache: t.TempDir(), gitconfig: gitconfig}
}

func (h *harness) run(stdin string, args ...string) (string, error) {
	h.t.Helper()
	var out bytes.Buffer
	err := run(
		context.Background(),
		env{
			dir:      h.repo.Dir,
			cacheDir: h.cache,
			stdin:    strings.NewReader(stdin),
			stdout:   &out,
			glab:     h.glab,
			gh:       h.gh,
		},
		args,
	)
	return out.String(), err
}

func (h *harness) mustRun(stdin string, args ...string) string {
	h.t.Helper()
	out, err := h.run(stdin, args...)
	if err != nil {
		h.t.Fatalf("gr %s: %v\n%s", strings.Join(args, " "), err, out)
	}
	return out
}

func (h *harness) exportDir(id string) string {
	h.t.Helper()
	dir := strings.TrimSpace(h.mustRun("", "export", "--dir"))
	if want := filepath.Join(h.repo.Dir, ".git", "guided-review", "exports", id); dir != want {
		h.t.Fatalf("export dir %q, want %q", dir, want)
	}
	return dir
}

func assertContains(t *testing.T, out string, wants ...string) {
	t.Helper()
	for _, w := range wants {
		if !strings.Contains(out, w) {
			t.Fatalf("output lacks %q:\n%s", w, out)
		}
	}
}

